// Reuse the actual web score. Only sampling and the final S16 transport differ.
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const assert = require("node:assert/strict");
const app = path.join(__dirname, "..");
const src = fs.readFileSync(path.join(app, "../../design/pixel-badge/sound.js"), "utf8");
const scope = {window: {}, localStorage: {getItem: () => null}};
vm.runInNewContext(src, scope);
const sound = new scope.window.BadgeSound();
const rate = 16000;
const buffers = [], tracks = [], scores = new Map();
let frames = 0;

function render(notes) {
  const end = Math.max(...notes.map(n => n.delay + n.dur + 0.02));
  const samples = new Float64Array(Math.ceil(end * rate));
  for (const n of notes) {
    let phase = 0;
    const start = Math.round(n.delay * rate);
    for (let i=0; i < Math.round((n.dur+0.02)*rate); i++) {
      const t = i / rate;
      const freq = n.freq * Math.pow(n.slideTo / n.freq, Math.min(t/n.dur,1));
      const wave = n.type === "sine" ? Math.sin(phase*2*Math.PI) : n.type === "triangle"
        ? 2*Math.asin(Math.sin(phase*2*Math.PI))/Math.PI : bandLimitedSquare(phase,freq);
      const ramp = Math.max(0, Math.min(1,(t-0.012)/(n.dur-0.012)));
      const gain = t < 0.012 ? 0.0001+(n.gain-0.0001)*t/0.012 : n.gain*Math.pow(0.0001/n.gain,ramp);
      samples[start+i] += gain*wave;
      phase = (phase+freq/rate)%1;
    }
  }
  const pcm = Buffer.alloc(samples.length*2);
  for (let i=0; i < samples.length; i++) {
    const value = Math.round(32767*samples[i]);
    assert(Math.abs(value) < 32767, "score clips");
    pcm.writeInt16LE(value, i*2);
  }
  return pcm;
}
function bandLimitedSquare(phase, freq) {
  let value=0;
  for (let k=1; k*freq < rate/2; k+=2) value += Math.sin(2*Math.PI*phase*k)/k;
  return 4*value/Math.PI;
}

for (const [,name] of src.matchAll(/case "(\w+)":/g)) {
  if (/^(ds|cl)[A-Z]/.test(name)) continue;
  const notes=[];
  sound.tone=(freq,{delay=0,dur=0.09,type="triangle",gain=0.06,slideTo=freq}={}) =>
    notes.push({freq,delay,dur,type,gain,slideTo});
  sound.play(name);
  assert(notes.length, name);
  const key=JSON.stringify(notes);
  if (!scores.has(key)) {
    const pcm=render(notes);
    scores.set(key, [frames, pcm.length/2]);
    frames += pcm.length/2;
    buffers.push(pcm);
  }
  tracks.push([name,...scores.get(key)]);
}
const output = new Map([
  ["assets/pet_tones.pcm", Buffer.concat(buffers)],
  ["pet_tones.inc", Buffer.from("// Generated by authoring/bake_tones.cjs from design/pixel-badge/sound.js.\n"+
    tracks.map(([name,offset,count]) => `    {"${name}", ${offset}, ${count}},\n`).join(""))]
]);
for (const [filename, bytes] of output) {
  const dest=path.join(app,filename);
  if (process.argv.includes("--check")) assert(fs.readFileSync(dest).equals(bytes),filename);
  else {fs.mkdirSync(path.dirname(dest),{recursive:true}); fs.writeFileSync(dest,bytes);}
}
console.log(`${tracks.length} GPT events, ${scores.size} unique melodies, ${frames} mono 16 kHz samples`);
